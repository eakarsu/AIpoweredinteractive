const express = require('express');
const router = express.Router();
const pool = require('../db');

router.get('/', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM troubleshooting ORDER BY category, title');
    res.json(result.rows);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.get('/:id', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM troubleshooting WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.post('/', async (req, res) => {
  try {
    const { title, symptom, cause, solution, difficulty, category, vehicle_id } = req.body;
    const result = await pool.query(
      'INSERT INTO troubleshooting (title, symptom, cause, solution, difficulty, category, vehicle_id) VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *',
      [title, symptom, cause, solution, difficulty, category, vehicle_id || null]
    );
    res.status(201).json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.put('/:id', async (req, res) => {
  try {
    const { title, symptom, cause, solution, difficulty, category, vehicle_id } = req.body;
    const result = await pool.query(
      'UPDATE troubleshooting SET title=$1, symptom=$2, cause=$3, solution=$4, difficulty=$5, category=$6, vehicle_id=$7 WHERE id=$8 RETURNING *',
      [title, symptom, cause, solution, difficulty, category, vehicle_id || null, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.delete('/:id', async (req, res) => {
  try {
    const result = await pool.query('DELETE FROM troubleshooting WHERE id = $1 RETURNING *', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json({ message: 'Deleted successfully' });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

module.exports = router;
