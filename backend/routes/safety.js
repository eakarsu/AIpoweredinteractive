const express = require('express');
const router = express.Router();
const pool = require('../db');

router.get('/', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM safety_features ORDER BY category, name');
    res.json(result.rows);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.get('/:id', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM safety_features WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.post('/', async (req, res) => {
  try {
    const { name, description, how_it_works, activation_conditions, category, vehicle_id } = req.body;
    const result = await pool.query(
      'INSERT INTO safety_features (name, description, how_it_works, activation_conditions, category, vehicle_id) VALUES ($1,$2,$3,$4,$5,$6) RETURNING *',
      [name, description, how_it_works, activation_conditions, category, vehicle_id || null]
    );
    res.status(201).json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.put('/:id', async (req, res) => {
  try {
    const { name, description, how_it_works, activation_conditions, category, vehicle_id } = req.body;
    const result = await pool.query(
      'UPDATE safety_features SET name=$1, description=$2, how_it_works=$3, activation_conditions=$4, category=$5, vehicle_id=$6 WHERE id=$7 RETURNING *',
      [name, description, how_it_works, activation_conditions, category, vehicle_id || null, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.delete('/:id', async (req, res) => {
  try {
    const result = await pool.query('DELETE FROM safety_features WHERE id = $1 RETURNING *', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json({ message: 'Deleted successfully' });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

module.exports = router;
