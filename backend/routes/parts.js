const express = require('express');
const router = express.Router();
const pool = require('../db');

router.get('/', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM parts ORDER BY category, name');
    res.json(result.rows);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.get('/:id', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM parts WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.post('/', async (req, res) => {
  try {
    const { part_number, name, description, category, price, compatibility, in_stock } = req.body;
    const result = await pool.query(
      'INSERT INTO parts (part_number, name, description, category, price, compatibility, in_stock) VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *',
      [part_number, name, description, category, price, compatibility, in_stock !== false]
    );
    res.status(201).json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.put('/:id', async (req, res) => {
  try {
    const { part_number, name, description, category, price, compatibility, in_stock } = req.body;
    const result = await pool.query(
      'UPDATE parts SET part_number=$1, name=$2, description=$3, category=$4, price=$5, compatibility=$6, in_stock=$7 WHERE id=$8 RETURNING *',
      [part_number, name, description, category, price, compatibility, in_stock, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.delete('/:id', async (req, res) => {
  try {
    const result = await pool.query('DELETE FROM parts WHERE id = $1 RETURNING *', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json({ message: 'Deleted successfully' });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

module.exports = router;
