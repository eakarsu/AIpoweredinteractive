const express = require('express');
const router = express.Router();
const pool = require('../db');

router.get('/', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM tutorials ORDER BY category, title');
    res.json(result.rows);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.get('/:id', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM tutorials WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.post('/', async (req, res) => {
  try {
    const { title, description, category, difficulty, duration, steps, tools_needed, vehicle_id } = req.body;
    const result = await pool.query(
      'INSERT INTO tutorials (title, description, category, difficulty, duration, steps, tools_needed, vehicle_id) VALUES ($1,$2,$3,$4,$5,$6,$7,$8) RETURNING *',
      [title, description, category, difficulty, duration, steps, tools_needed, vehicle_id || null]
    );
    res.status(201).json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.put('/:id', async (req, res) => {
  try {
    const { title, description, category, difficulty, duration, steps, tools_needed, vehicle_id } = req.body;
    const result = await pool.query(
      'UPDATE tutorials SET title=$1, description=$2, category=$3, difficulty=$4, duration=$5, steps=$6, tools_needed=$7, vehicle_id=$8 WHERE id=$9 RETURNING *',
      [title, description, category, difficulty, duration, steps, tools_needed, vehicle_id || null, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.delete('/:id', async (req, res) => {
  try {
    const result = await pool.query('DELETE FROM tutorials WHERE id = $1 RETURNING *', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json({ message: 'Deleted successfully' });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

module.exports = router;
